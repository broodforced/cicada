package report

import (
	"fmt"
	"strings"

	"github.com/broodforced/cicada/internal/schema"
)

const version = "0.1.0"

var impactMap = map[string]string{
	"xss":                    "An attacker can execute arbitrary JavaScript in the context of the victim's browser session, potentially stealing session tokens, credentials, or performing actions on behalf of the user.",
	"sql-injection":          "An attacker may be able to read, modify, or delete data from the database, potentially compromising the entire application and its users' data.",
	"ssrf":                   "An attacker can make the server perform requests to internal services, potentially accessing sensitive internal resources or cloud metadata endpoints.",
	"remote-code-execution":  "An attacker can execute arbitrary commands on the server, leading to complete system compromise.",
	"cors-misconfiguration":  "An attacker can read sensitive data from the API from a malicious origin, bypassing same-origin policy protections.",
	"open-redirect":          "An attacker can redirect users to a malicious site, which can be used for phishing attacks or credential theft.",
	"information-disclosure": "Sensitive information is exposed that could aid an attacker in further exploitation of the application.",
	"subdomain-takeover":     "An attacker can claim the subdomain and serve arbitrary content, potentially impersonating the organization.",
}

func evidenceSteps(f schema.Finding) string {
	var steps []string
	if f.Evidence.Request != "" {
		req := f.Evidence.Request
		if strings.HasPrefix(req, "curl") {
			steps = append(steps, fmt.Sprintf("2. Execute the following request:\n```\n%s\n```", req))
		} else {
			steps = append(steps, fmt.Sprintf("2. Send the following request:\n```\n%s\n```", trunc(req, 500)))
		}
	}
	if f.Evidence.Response != "" {
		steps = append(steps, fmt.Sprintf("3. Observe the response:\n```\n%s\n```", trunc(f.Evidence.Response, 500)))
	}
	if len(steps) == 0 {
		return "2. Observe the vulnerable behavior described above."
	}
	return strings.Join(steps, "\n")
}

func impact(f schema.Finding) string {
	cat := strings.ToLower(f.Category)
	if imp, ok := impactMap[cat]; ok {
		return imp
	}
	return fmt.Sprintf("This %s severity %s finding could impact the security of the application and its users.",
		f.Severity, f.Category)
}

// H1Report is one finding's pre-filled template plus its source finding.
type H1Report struct {
	Finding schema.Finding
	Report  string
}

// GenerateH1 renders a single finding as a HackerOne-style markdown report.
func GenerateH1(f schema.Finding) string {
	refs := ""
	if f.Reference != "" {
		refs = fmt.Sprintf("- References: %s\n", f.Reference)
	}
	return fmt.Sprintf(`## Summary

%s

**Severity:** %s
**Category:** %s
**Target:** %s

## Description

%s

## Steps to Reproduce

1. Navigate to: `+"`"+`%s`+"`"+`
%s

## Impact

%s

## Supporting Material / References

- Tool: %s
- Confidence: %s
%s
---
*Generated by Cicada v%s*
`,
		f.Title,
		strings.ToUpper(f.Severity),
		f.Category,
		f.Target,
		f.Detail,
		f.Target,
		evidenceSteps(f),
		impact(f),
		f.Tool,
		f.Confidence,
		refs,
		version)
}

// GenerateBatch builds templates for every actionable (critical/high/medium) finding.
func GenerateBatch(findings []schema.Finding) []H1Report {
	var out []H1Report
	for _, f := range findings {
		switch strings.ToLower(f.Severity) {
		case "critical", "high", "medium":
			out = append(out, H1Report{Finding: f, Report: GenerateH1(f)})
		}
	}
	return out
}