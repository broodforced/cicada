from shared.schema import Finding


class H1Template:

	@staticmethod
	def generate(finding, program_name=""):
		return f"""## Summary

{finding.title}

**Severity:** {finding.severity.upper()}
**Category:** {finding.category}
**Target:** {finding.target}

## Description

{finding.detail}

## Steps to Reproduce

1. Navigate to: `{finding.target}`
{H1Template._evidence_steps(finding)}

## Impact

{H1Template._impact(finding)}

## Supporting Material / References

- Tool: {finding.tool}
- Confidence: {finding.confidence}
{f"- References: {finding.reference}" if finding.reference else ""}

---
*Generated by Cicada v0.1.0*
"""

	@staticmethod
	def generate_batch(findings, program_name=""):
		reports = []
		actionable = [f for f in findings if f.severity.lower() in ("critical", "high", "medium")]
		for f in actionable:
			reports.append({
				"finding": f,
				"report": H1Template.generate(f, program_name),
			})
		return reports

	@staticmethod
	def _evidence_steps(finding):
		steps = []
		if finding.evidence.request:
			req = finding.evidence.request
			if req.startswith("curl"):
				steps.append(f"2. Execute the following request:\n```\n{req}\n```")
			else:
				steps.append(f"2. Send the following request:\n```\n{req[:500]}\n```")
		if finding.evidence.response:
			steps.append(f"3. Observe the response:\n```\n{finding.evidence.response[:500]}\n```")
		return "\n".join(steps) if steps else "2. Observe the vulnerable behavior described above."

	@staticmethod
	def _impact(finding):
		impact_map = {
			"xss": "An attacker can execute arbitrary JavaScript in the context of the victim's browser session, potentially stealing session tokens, credentials, or performing actions on behalf of the user.",
			"sql-injection": "An attacker may be able to read, modify, or delete data from the database, potentially compromising the entire application and its users' data.",
			"ssrf": "An attacker can make the server perform requests to internal services, potentially accessing sensitive internal resources or cloud metadata endpoints.",
			"remote-code-execution": "An attacker can execute arbitrary commands on the server, leading to complete system compromise.",
			"cors-misconfiguration": "An attacker can read sensitive data from the API from a malicious origin, bypassing same-origin policy protections.",
			"open-redirect": "An attacker can redirect users to a malicious site, which can be used for phishing attacks or credential theft.",
			"information-disclosure": "Sensitive information is exposed that could aid an attacker in further exploitation of the application.",
			"subdomain-takeover": "An attacker can claim the subdomain and serve arbitrary content, potentially impersonating the organization.",
		}
		cat = finding.category.lower()
		return impact_map.get(cat, f"This {finding.severity} severity {finding.category} finding could impact the security of the application and its users.")
